clear;
clc;

% Stage control: keep [1] until the Stage-2 gate is accepted.
scenario_indices = 1;

% [K, M, N] -- filename order remains (N, K, M).
scenarios = [ ...
     6,  30, 2000; ...
     6,  50, 1000; ...
     6, 100, 1000; ...
    10,  30, 1000; ...
    10,  50, 1000; ...
    10, 100, 1000; ...
    15,  30, 1000; ...
    15,  50, 1000; ...
    15, 100, 1000; ...
     6,  20,  500; ...
     6,  40,  500; ...
     6,  60,  500; ...
     6,  80,  500; ...
     4,  30,  500; ...
     8,  30,  500; ...
    12,  30,  500; ...
    16,  30,  500];

num_antenna = 1;
num_sr = 3;
tau = 20;
power_f = 0.2;
D = 1;
f = 1900;
Hb = 15;
Hm = 1.65;
d0 = 0.01;
d1 = 0.05;
max_iter = 50;
placeholder_nu = 1;
nu_percentile_levels = [50, 75, 90, 95, 99];
sigma2_percentile_levels = [0, 1, 5, 10, 25, 50, 75, 90, 95, 99, 100];

output_dir = 'New';
if ~isfolder(output_dir)
    mkdir(output_dir);
end
manifest_file = fullfile(output_dir, 'scenario_manifest.csv');

for scenario_index = scenario_indices
    num_ue = scenarios(scenario_index, 1);
    num_ap = scenarios(scenario_index, 2);
    num_sam = scenarios(scenario_index, 3);
    seed = 1712 + scenario_index;
    rng(seed, 'twister');
    scenario_timer = tic;

    fprintf('\nSCENARIO_START K=%d M=%d T=%d N=%d seed=%d\n', ...
        num_ue, num_ap, num_sr, num_sam, seed);

    % Pass A: channel, geometry, and non-Log baselines only.
    [betas, Gammas, Phii_cf, R_equal, R_frac, ~, ...
        power_eq, power_frac, ~, ...
        rcs_values, ap_locations, sr_locations, ...
        q_a_all, q_b_all, q_c_all] = downlink_ISAC_sumrate_data( ...
        num_sam, num_ap, num_ue, num_sr, num_antenna, tau, power_f, ...
        Hb, Hm, f, d0, d1, D, placeholder_nu, false);

    sigma2_equal = inf(num_sam, 1);
    fim_denom = nan(num_sam, 1);
    g_max_error = 0;
    for n = 1:num_sam
        gamma_n = reshape(Gammas(n,:,:), num_ap, num_ue);
        power_eq_n = reshape(power_eq(n,:,:), num_ap, num_ue);
        p = sum(gamma_n .* power_eq_n, 2);
        g_max_error = max(g_max_error, max(abs(p - 1)));

        q_a = reshape(q_a_all(n,:,:), num_ap, 1);
        q_b = reshape(q_b_all(n,:,:), num_ap, 1);
        q_c = reshape(q_c_all(n,:,:), num_ap, 1);
        sa = q_a' * p;
        sb = q_b' * p;
        sc = q_c' * p;
        fim_denom(n) = sa * sb - sc^2;
        if fim_denom(n) > 0
            sigma2_equal(n) = (sa + sb) / fim_denom(n);
        end
    end

    singular_fraction = mean(fim_denom <= 0);
    finite_sigma2 = sigma2_equal(isfinite(sigma2_equal));
    sigma2_percentiles = prctile( ...
        finite_sigma2, sigma2_percentile_levels);
    nu_vec = prctile(finite_sigma2, nu_percentile_levels);
    nu_main = nu_vec(4);

    if g_max_error > 1e-12
        error('gen_all_scenarios:EqualPowerGate', ...
            'G1 failed: max |g_m-1| = %.17g.', g_max_error);
    end

    % Pass B: five independent Log-approximation sweeps.
    power_log_all = zeros(num_sam, num_ap, num_ue, numel(nu_vec));
    R_log_all = zeros(numel(nu_vec), num_sam);
    status_all = zeros(num_sam, numel(nu_vec), 'uint8');
    converged_all = false(num_sam, numel(nu_vec));
    for nu_index = 1:numel(nu_vec)
        fprintf('PASS_B nu_index=%d/%d nu=%.12g\n', ...
            nu_index, numel(nu_vec), nu_vec(nu_index));
        [power_nu, rate_nu, status_nu, converged_nu] = ...
            solve_logapprox_batch( ...
            betas, Gammas, Phii_cf, q_a_all, q_b_all, q_c_all, ...
            nu_vec(nu_index), power_f, num_antenna, max_iter);
        power_log_all(:,:,:,nu_index) = power_nu;
        R_log_all(nu_index,:) = rate_nu;
        status_all(:,nu_index) = status_nu;
        converged_all(:,nu_index) = converged_nu;
        if mean(status_nu == 2) > 0.01
            error('gen_all_scenarios:SolverFailureGate', ...
                'Status-2 fraction %.4f exceeds 1%% at nu index %d.', ...
                mean(status_nu == 2), nu_index);
        end
    end

    % Backward-compatible p95 aliases.
    power_log = power_log_all(:,:,:,4);
    R_log = R_log_all(4,:);

    wall_clock = toc(scenario_timer);
    solved_fraction = mean(status_all(:,4) == 0);
    infeasible_fraction = mean(status_all(:,4) == 1);
    fallback_fraction = mean(status_all(:,4) == 2);
    equal_power_mean_rate = mean(R_equal);
    log_approx_mean_rate = mean(R_log);

    filename = sprintf( ...
        'dl_isac_sumrate_data_%d_%d_%d.mat', ...
        num_sam, num_ue, num_ap);
    output_file = fullfile(output_dir, filename);
    save(output_file, '-v7.3', ...
        'betas', 'Gammas', 'Phii_cf', 'R_equal', 'R_frac', 'R_log', ...
        'rcs_values', 'ap_locations', 'sr_locations', ...
        'q_a_all', 'q_b_all', 'q_c_all', ...
        'power_eq', 'power_frac', 'power_log', ...
        'sigma2_equal', 'sigma2_percentile_levels', 'sigma2_percentiles', ...
        'nu_percentile_levels', 'nu_vec', 'nu_main', ...
        'power_log_all', 'R_log_all', 'status_all', 'converged_all', ...
        'num_sr', 'num_antenna', 'seed', 'max_iter');

    manifest_row = table( ...
        num_ue, num_ap, num_sr, num_sam, nu_main, ...
        string(mat2str(nu_vec, 12)), 100 * singular_fraction, ...
        100 * solved_fraction, 100 * infeasible_fraction, ...
        equal_power_mean_rate, log_approx_mean_rate, max_iter, ...
        wall_clock, seed, string(filename), ...
        'VariableNames', {'K','M','T','num_sam','nu_main','nu_vec', ...
        'singular_percent','solved_percent','infeasible_percent', ...
        'equal_power_mean_rate','log_approx_mean_rate','max_iter', ...
        'wall_clock_seconds','seed','filename'});
    if isfile(manifest_file)
        old_manifest = readtable(manifest_file, 'TextType', 'string');
        same_scenario = old_manifest.K == num_ue & ...
            old_manifest.M == num_ap & old_manifest.T == num_sr & ...
            old_manifest.num_sam == num_sam;
        old_manifest(same_scenario,:) = [];
        manifest = [old_manifest; manifest_row]; %#ok<AGROW>
    else
        manifest = manifest_row;
    end
    writetable(manifest, manifest_file);

    fprintf(['GATE K=%d M=%d T=%d N=%d G1=%.17g G2=%.6f%% ' ...
        'nu_main=%.12g solved=%.6f%% infeasible=%.6f%% fallback=%.6f%% ' ...
        'equal_rate=%.12g log_rate=%.12g wall=%.3fs file=%s\n'], ...
        num_ue, num_ap, num_sr, num_sam, g_max_error, ...
        100 * singular_fraction, nu_main, 100 * solved_fraction, ...
        100 * infeasible_fraction, 100 * fallback_fraction, ...
        equal_power_mean_rate, log_approx_mean_rate, wall_clock, output_file);
    fprintf('SIGMA2_PERCENTILES levels=%s values=%s\n', ...
        mat2str(sigma2_percentile_levels), ...
        mat2str(sigma2_percentiles, 12));
    fprintf('NU_VEC %s\n', mat2str(nu_vec, 12));
end
